// Same-version repair: rebuild the changed host from source and reuse only a
// cryptographically pinned, previously audited offline runtime payload.
import {readFile,writeFile,mkdir,rm,readdir,cp} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {build,transformSync} from 'esbuild';
import fuses from '@electron/fuses';
import {extractAll,extractFile,createPackage,listPackage,statFile} from '@electron/asar';
import {fileHash} from './installer-audit.mjs';
import {verifyBundledHost} from './ned-host-smoke.mjs';
import {hostAliases} from './ned-host-build.mjs';
const baselineCommit='9aeb3cb66cec2be391beddf7548f558ef39aac61';
const baselineInstallerSha256='c8d8aa63269118a1fa9d732dc0347631aefbf6e72992fac3c0fb2c276563c326';
const oldLabel='프로젝트 폴더 열기 · 바탕화면 / 즐겨찾기',newLabel='프로젝트 폴더 열기';
export async function rebuildBaseline(root,version,revision){
 if(version!=='0.3.6'||revision!=='rebuild1')throw Error('Unsupported same-version rebuild');
 const audit=JSON.parse(await readFile(path.join(root,'downloads/Ned-0.3.6-installer-audit.json'),'utf8'));
 if(audit.sourceCommit!==baselineCommit||audit.installer.sha256!==baselineInstallerSha256)throw Error('Wrong baseline audit');
 return audit;
}
export async function payloadInventory(root){
 const result={};
 async function visit(relative=''){
  for(const item of await readdir(path.join(root,relative),{withFileTypes:true})){
   const name=relative?relative+'/'+item.name:item.name;
   if(item.isDirectory())await visit(name);
   else if(item.isFile())result[name]=await fileHash(path.join(root,name));
   else throw Error('Unsupported payload link: '+name);
  }
 }
 await visit();return result;
}
export async function prepareRebuild(root,cache,staged,version,revision,sourceCommit,seven){
 const baseline=await rebuildBaseline(root,version,revision);
 if(execFileSync('git',['diff','HEAD','--name-only','--','distribution','src','scripts','package.json','package-lock.json','docs'],{cwd:root,encoding:'utf8'}).trim())throw Error('Commit rebuild inputs first');
 const git=(...args)=>execFileSync('git',args,{cwd:root,encoding:'utf8',maxBuffer:16*1024*1024});
 const originalTs=git('show',baselineCommit+':distribution/ned/main.ts');
 if(originalTs.replace(oldLabel,newLabel)!==await readFile(path.join(root,'distribution/ned/main.ts'),'utf8'))throw Error('Host source change exceeds the pinned menu repair');
 const codeChanges=git('diff','--name-only',baselineCommit,sourceCommit,'--','src','distribution').trim().split('\n').filter(Boolean);
 if(codeChanges.some(f=>!['distribution/ned/main.ts','distribution/ned/installer.nsi'].includes(f)))throw Error('Runtime changes require a full runtime build');
 const original=path.join(cache,revision,'base.exe');
 if(await fileHash(original)!==baseline.installer.sha256)throw Error('Baseline installer integrity failed');
 await rm(staged,{recursive:true,force:true});await mkdir(staged,{recursive:true});
 execFileSync(seven,['x','-y','-o'+staged,original],{stdio:'ignore'});
 // Installer-owned plugins must be regenerated by NSIS, not installed as app files.
 await rm(path.join(staged,'$PLUGINSDIR'),{recursive:true,force:true});
 const wire=await fuses.getCurrentFuseWire(path.join(staged,'Ned.exe'));
 if(wire[fuses.FuseV1Options.EnableEmbeddedAsarIntegrityValidation]!==48)throw Error('Host archive repair requires disabled embedded ASAR validation');
 const before=await payloadInventory(staged);
 const archive=path.join(staged,'resources/app.asar');
 const originalMain=extractFile(archive,'main.cjs');
 const app=JSON.parse(extractFile(archive,'package.json'));
 if(app.name!=='ned'||app.version!==version)throw Error('Wrong baseline application');
 const out=path.join(cache,revision,'host-build');await mkdir(out,{recursive:true});
 await build({bundle:true,platform:'node',format:'cjs',target:'node22',logLevel:'info',legalComments:'eof',entryPoints:[path.join(root,'distribution/ned/main.ts')],outfile:path.join(out,'main.cjs'),external:['electron'],alias:hostAliases,define:{NED_VERSION:JSON.stringify(version)}});
 const fresh=await readFile(path.join(out,'main.cjs'));
 const token=text=>transformSync('let value = '+JSON.stringify(text),{charset:'ascii',target:'node22'}).code.match(/let value = (.+);/)[1];
 const oldToken=token(oldLabel),newToken=token(newLabel),text=originalMain.toString();
 if(text.split(oldToken).length!==2||!fresh.equals(Buffer.from(text.replace(oldToken,newToken))))throw Error('Compiled host differs beyond the menu label');
 const hostModuleSmoke=verifyBundledHost(fresh);
 const appDir=path.join(out,'app');await rm(appDir,{recursive:true,force:true});extractAll(archive,appDir);await writeFile(path.join(appDir,'main.cjs'),fresh);
 const replacement=path.join(out,'app.asar');await createPackage(appDir,replacement);
 const entries=listPackage(archive).sort();
 if(JSON.stringify(entries)!==JSON.stringify(listPackage(replacement).sort()))throw Error('Unexpected ASAR entry change');
 for(const entry of entries){const name=entry.slice(1);if(name==='main.cjs'||statFile(archive,name).files)continue;
  if(!extractFile(archive,name).equals(extractFile(replacement,name)))throw Error('Unexpected ASAR dependency change');}
 await cp(replacement,archive);
 await cp(path.join(root,'docs/offline-setup.md'),path.join(staged,'resources/ned/GETTING_STARTED.md'));
 const provenance={schemaVersion:1,product:'Ned',version,buildRevision:revision,sourceCommit,baselineSourceCommit:baselineCommit,baselineInstallerSha256,hostModuleSmoke,compiledHostOnlyMenuLabelChanged:true,embeddedAsarIntegrityValidation:false,windowsAcceptance:false};
 await writeFile(path.join(staged,'resources/ned/build-info.json'),JSON.stringify(provenance,null,2)+'\n');
 const after=await payloadInventory(staged),allowed=new Set(['resources/app.asar','resources/ned/GETTING_STARTED.md','resources/ned/build-info.json']);
 const changes=[...new Set([...Object.keys(before),...Object.keys(after)])].filter(name=>before[name]!==after[name]);
 if(changes.some(name=>!allowed.has(name))||changes.length!==3)throw Error('Unexpected runtime payload changes');
 await writeFile(path.join(cache,revision,'provenance.json'),JSON.stringify({...provenance,changedFiles:changes,payloadInventory:after},null,2)+'\n');
 return baseline;
}
