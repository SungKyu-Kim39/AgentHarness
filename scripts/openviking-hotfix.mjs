import { readFile, writeFile, mkdir, cp, rm, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { verifyAsciiTree, verifyAsciiTar } from './package-paths.mjs';

const project = path.resolve(import.meta.dirname, '..');
const runtime = path.join(project, 'vendor/runtime/windows-x64/openviking');
const output = path.join(project, 'release/desktop');
const name = 'L-Vibe-openviking-loopback-fix-1';
const root = path.join(output, name);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
execFileSync('git', ['diff', '--quiet'], { cwd: project });
execFileSync('git', ['diff', '--cached', '--quiet'], { cwd: project });
const oldManifest = await readFile(path.join(runtime, 'manifest.json'));
const oldManifestHash = '8d2fbf5aef25d431433feb5f34f09cbf908c025476cb7ac024f6e3674b473a3d';
if (hash(oldManifest) !== oldManifestHash) throw new Error('Build this repair from the original 0.2.2/0.2.3 Python bundle');
const manifest = JSON.parse(oldManifest);
const entry = manifest.files.find(file => file.path === 'launch.py');
if (!entry) throw new Error('Missing baseline launcher entry');
const original = await readFile(path.join(runtime, 'launch.py'));
if (hash(original) !== entry.sha256) throw new Error('Baseline launcher differs from the original manifest');
const updated = await readFile(path.join(project, 'scripts/openviking-launch.py'));
if (hash(updated) === hash(original)) throw new Error('Launcher fix is missing');
entry.sha256 = hash(updated);
const newManifest = Buffer.from(JSON.stringify(manifest, null, 2) + '\n');
const pins = { OLD_MANIFEST: oldManifestHash, OLD_LAUNCH: hash(original), NEW_MANIFEST: hash(newManifest), NEW_LAUNCH: hash(updated) };
await rm(root, { recursive: true, force: true }); await mkdir(root, { recursive: true });
await writeFile(path.join(root, 'manifest.json'), newManifest);
await writeFile(path.join(root, 'launch.py'), updated);
await writeFile(path.join(root, 'original-launch.py'), original);
let installer = await readFile(path.join(project, 'distribution/openviking-loopback-fix.py'), 'utf8');
for (const [key, value] of Object.entries(pins)) installer = installer.replaceAll('@' + key + '@', value);
await writeFile(path.join(root, 'apply-fix.py'), installer);
await writeFile(path.join(root, 'APPLY_FIX.cmd'), '@echo off\r\n"%LOCALAPPDATA%\\Programs\\L-Vibe\\resources\\runtime\\windows-x64\\openviking\\python\\python.exe" -I -B "%~dp0apply-fix.py"\r\nset "L_VIBE_FIX_RESULT=%ERRORLEVEL%"\r\npause\r\nexit /b %L_VIBE_FIX_RESULT%\r\n');
await cp(path.join(project, 'distribution/openviking-import-check.py'), path.join(root, 'check-import.py'));
await writeFile(path.join(root, 'CHECK_IMPORT.cmd'), '@echo off\r\n"%LOCALAPPDATA%\\Programs\\L-Vibe\\resources\\runtime\\windows-x64\\openviking\\python\\python.exe" -I -B "%~dp0check-import.py"\r\nset "L_VIBE_CHECK_RESULT=%ERRORLEVEL%"\r\necho EXIT_CODE=%L_VIBE_CHECK_RESULT%\r\npause\r\nexit /b %L_VIBE_CHECK_RESULT%\r\n');
await cp(path.join(project, 'LICENSE'), path.join(root, 'LICENSE'));
await writeFile(path.join(root, 'README.txt'), 'L-Vibe OpenViking Windows loopback fix 1\n\n1. L-Vibe를 완전히 종료합니다.\n2. 이 TGZ를 별도 폴더에 압축 해제합니다.\n3. APPLY_FIX.cmd를 실행합니다. 관리자 권한이나 추가 설치는 필요하지 않습니다.\n4. status가 applied 또는 already-applied이면 L-Vibe를 다시 실행합니다.\n\n계속 실패하면 앱을 종료하고 CHECK_IMPORT.cmd를 실행하여 출력 결과를 확인하세요. 이 진단은 모델 설정·실제 API 키를 읽지 않고 설치된 정책으로 모듈만 검사합니다.\n\n지원 대상: 원본 Python manifest가 일치하는 0.2.2/0.2.3 설치본.\n이 패치는 Windows asyncio의 내부 TCP 소켓 쌍만 허용합니다. 일반 로컬 포트·외부 연결 제한은 유지합니다.\nlaunch.py와 해당 manifest만 교체하며 설정 JSON·암호화 설정·대화·지식 데이터는 읽거나 바꾸지 않습니다.\n원본 복구 사본은 %APPDATA%\\L-Vibe\\openviking\\patch-backups에 남깁니다.\n이 패치에는 새 Desktop 오류 진단 UI가 포함되지 않습니다.\n');
const metadata = { name, targetVersions: ['0.2.2', '0.2.3'], sourceCommit: execFileSync('git', ['rev-parse', 'HEAD'], { cwd: project, encoding: 'utf8' }).trim(),
  ...pins, pathEncoding: 'ascii', modifies: ['launch.py', 'manifest.json'], preservesUserConfiguration: true, downloadsDependencies: false };
await writeFile(path.join(root, 'PATCH-MANIFEST.json'), JSON.stringify(metadata, null, 2) + '\n');
await verifyAsciiTree(root);
const archive = path.join(output, name + '.tgz');
execFileSync('tar', ['-I', 'gzip -1', '-cf', archive, '-C', output, name]);
const paths = verifyAsciiTar(archive);
const sha256 = hash(await readFile(archive));
await writeFile(archive + '.sha256', sha256 + '  ' + path.basename(archive) + '\n');
console.log(JSON.stringify({ archive, bytes: (await stat(archive)).size, sha256, paths, ...metadata }, null, 2));
