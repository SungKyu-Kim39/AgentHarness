import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { VisualStudioBuild } from '../distribution/vs-build';
test('VS build inspection discovers exact configurations; approval freezes inputs and rejects changed project files', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'ned-msbuild-')); t.after(() => rm(root, { recursive: true, force: true }));
  const project = path.join(root, 'project'); await mkdir(project);
  const xml = '<Project><ItemGroup><ProjectConfiguration Include="Debug|x64" /><ProjectConfiguration Include="Release|Win32" /></ItemGroup><PropertyGroup><PlatformToolset>v142</PlatformToolset><WindowsTargetPlatformVersion>10.0.19041.0</WindowsTargetPlatformVersion></PropertyGroup></Project>';
  await writeFile(path.join(project, 'app.vcxproj'), xml);
  await writeFile(path.join(project, 'app.sln'), 'Global\nGlobalSection(SolutionConfigurationPlatforms) = preSolution\n Debug|x64 = Debug|x64\n Release|Win32 = Release|Win32\nEndGlobalSection\nEndGlobal\n');
  const binary = path.join(root, 'MSBuild.exe'); await writeFile(binary, 'synthetic-msbuild');
  const tools = async () => [{ name: 'VS2019 fixture', version: '16.11', installation: root, msbuild: binary }];
  let approvals = 0;
  const refused = new VisualStudioBuild(root, async (_message, detail) => { approvals++; assert.ok(detail.includes('/nr:false')); assert.ok(!detail.includes('cmd.exe')); return false; }, tools);
  const inspected = await refused.inspect(project);
  assert.equal(inspected.targets.length, 2);
  const target = inspected.targets.find(t => t.path === 'app.vcxproj')!;
  assert.deepEqual(target.configurations, [{ configuration: 'Debug', platform: 'x64' }, { configuration: 'Release', platform: 'Win32' }]);
  assert.deepEqual(target.toolsets, ['v142']); assert.deepEqual(target.sdkVersions, ['10.0.19041.0']);
  const input = { target: 'app.vcxproj', configuration: 'Debug', platform: 'x64', toolchain: 0 };
  await assert.rejects(refused.build(project, input), /거절/); assert.equal(approvals, 1);
  await assert.rejects(refused.build(project, { ...input, configuration: 'Debug;Injected=1' }), /먼저/); assert.equal(approvals, 1);
  const changed = new VisualStudioBuild(root, async () => { await writeFile(path.join(project, 'app.vcxproj'), xml + '<!-- externally changed -->'); return true; }, tools);
  await assert.rejects(changed.build(project, input), /입력이 변경/);
  await writeFile(path.join(project, 'app.vcxproj'), xml + '<ProjectReference Include="../outside.vcxproj" />');
  const outside = new VisualStudioBuild(root, async () => { assert.fail('Outside reference must be blocked before approval'); }, tools);
  await assert.rejects(outside.build(project, input), /폴더 밖/);
});
